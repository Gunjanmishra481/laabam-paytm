const TABLE: Record<Lang, Partial<Record<StringKey, string>>> = { en, ta, hi }

export function t(lang: Lang, key: StringKey): string {
  return TABLE[lang]?.[key] ?? en[key]
}

export function isStringKey(key: string): key is StringKey {
  return key in en
}

/** Fills {PLACEHOLDERS} in a string: fmt('Fix {N} lines', { N: 2 }). */
export function fmt(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{([A-Z_]+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}
